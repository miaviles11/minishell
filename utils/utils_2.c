#include "../includes/minishell.h"

int	is_quoted_token(const char *s)
{
	int	i;

	i = 0;
	while (s && s[i])
	{
		if (s[i] == '\'' || s[i] == '"' || s[i] == '\\')
			return (1);
		i++;
	}
	return (0);
}